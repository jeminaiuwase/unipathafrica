// Runs on every Netlify deploy (see netlify.toml). It records the site's source files so the
// owner can download the complete code from the admin console ("Download site code").
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const TEXT = ['netlify.toml', 'package.json', 'README.md', '.gitignore', 'scripts/snapshot.mjs', 'public/_redirects'];
for (const dir of ['netlify/functions', 'netlify/lib']) { try { readdirSync(join(root, dir)).filter((f) => f.endsWith('.mjs')).forEach((f) => TEXT.push(dir + '/' + f)); } catch {} }
const files = {};
for (const f of TEXT) { try { files[f] = readFileSync(join(root, f), 'utf8'); } catch {} }

const walk = (dir) => readdirSync(dir).flatMap((n) => { const p = join(dir, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
const publicFiles = walk(join(root, 'public')).map((p) => relative(join(root, 'public'), p).split('\\').join('/')).filter((p) => p !== '_redirects').sort();

writeFileSync(join(root, 'netlify/source-snapshot.mjs'), '// Generated by scripts/snapshot.mjs — do not edit by hand.\nexport default ' + JSON.stringify({ generatedAt: new Date().toISOString(), files, publicFiles }) + ';\n');
console.log('Source snapshot: ' + Object.keys(files).length + ' backend files, ' + publicFiles.length + ' public files');
